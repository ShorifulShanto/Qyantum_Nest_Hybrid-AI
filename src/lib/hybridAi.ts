import {
  getAI,
  GoogleAIBackend,
  getGenerativeModel,
  InferenceMode,
  InferenceSource,
  type HybridParams,
} from 'firebase/ai';
import { app } from './firebase';

export type HybridEngineSource =
  | 'On-Device (Gemini Nano)'
  | 'Cloud Fallback (Gemini 2.5 Flash)'
  | 'Server Streaming (Gemini)'
  | 'Server Fallback (Gemini Cloud)'
  | 'Local Archive Fallback'
  | 'On-Device Unavailable';

export interface HybridAIResult {
  text: string;
  source: HybridEngineSource;
  latencyMs: number;
  fallbackReason?: string;
  cached?: boolean;
}

export interface OnDeviceCapabilityStatus {
  onDeviceReady: boolean;
  availability: 'available' | 'downloadable' | 'downloading' | 'unavailable';
  label: string;
}

const SYSTEM_INSTRUCTION =
  'You are Quantum Nest AI, an expert astronomy, astrophysics, and Earth-science mission guide. Provide concise, scientifically accurate, and inspiring answers (2-4 sentences for quick questions) in plain text.';

let aiInstance: ReturnType<typeof getAI> | null = null;
try {
  if (app) {
    aiInstance = getAI(app, { backend: new GoogleAIBackend() });
  }
} catch {
  // Fallback routes cleanly to server Gemini proxy when Firebase AI is unconfigured
}

// Client-side response cache for instant repeat answers (keyed by routing mode + prompt)
const responseCache = new Map<string, HybridAIResult>();
const MAX_CACHE_ENTRIES = 60;

// Tracks when preview origin lacks Firebase App Check registration so Auto Hybrid skips repeated 401 delays
let firebaseCloudBlockedInSession = false;

function readClientCache(key: string): HybridAIResult | null {
  const cached = responseCache.get(key);
  if (!cached) return null;
  return { ...cached, cached: true };
}

function writeClientCache(key: string, result: HybridAIResult): void {
  if (responseCache.size >= MAX_CACHE_ENTRIES) {
    const oldestKey = responseCache.keys().next().value;
    if (oldestKey) responseCache.delete(oldestKey);
  }
  responseCache.set(key, result);
}

/**
 * Inspects Chrome Prompt API (window.LanguageModel) to report authentic on-device Gemini Nano readiness.
 */
export async function getOnDeviceCapability(): Promise<OnDeviceCapabilityStatus> {
  if (typeof globalThis === 'undefined') {
    return {
      onDeviceReady: false,
      availability: 'unavailable',
      label: 'Cloud Fallback Active (Gemini)',
    };
  }

  try {
    const g = globalThis as unknown as {
      LanguageModel?: {
        availability?: (opts?: unknown) => Promise<string>;
      };
    };

    if (g.LanguageModel && typeof g.LanguageModel.availability === 'function') {
      const state = await g.LanguageModel.availability();
      if (state === 'available' || state === 'readily') {
        return {
          onDeviceReady: true,
          availability: 'available',
          label: 'On-Device Ready (Gemini Nano)',
        };
      }
      if (state === 'downloadable' || state === 'after-download') {
        return {
          onDeviceReady: false,
          availability: 'downloadable',
          label: 'Gemini Nano Downloadable (Cloud Active)',
        };
      }
      if (state === 'downloading') {
        return {
          onDeviceReady: false,
          availability: 'downloading',
          label: 'Gemini Nano Downloading (Cloud Active)',
        };
      }
    }
  } catch {
    // ignore detection errors in restricted iframes
  }

  return {
    onDeviceReady: false,
    availability: 'unavailable',
    label: 'Cloud Fallback Active (Gemini)',
  };
}

function buildDomainFallbackText(prompt: string): string {
  const q = prompt.toLowerCase();
  if (q.includes('apod') || q.includes('picture of the day')) {
    return 'NASA Astronomy Picture of the Day (APOD) archives daily deep-sky photography, solar eruptions, and planetary close-ups curated by astronomers Robert Nemiroff and Jerry Bonnell. Open the Daily Capture (APOD) portal to scrub live NASA captures by date.';
  }
  if (q.includes('mars') || q.includes('habitable') || q.includes('kepler') || q.includes('trappist')) {
    return 'Habitability comparison: Mars has a thin 6 hPa CO2 atmosphere and cold -65°C mean temperatures, whereas exoplanet Kepler-452b (ESI 0.83) orbits a G2V Sun-like star every 385 days and TRAPPIST-1e (ESI 0.91) receives 66% of Earth solar irradiance inside its star’s liquid-water zone.';
  }
  if (q.includes('earth') || q.includes('magnetosphere') || q.includes('cme') || q.includes('solar')) {
    return 'Earth’s magnetosphere is generated by convective liquid iron in the outer core, deflecting charged solar wind and Coronal Mass Ejections (CMEs). Intense Earth-directed CMEs from active solar regions can elevate the planetary Kp index and drive high-latitude aurorae.';
  }
  if (q.includes('sonification') || q.includes('black hole') || q.includes('sound')) {
    return 'Astronomical sonification translates telemetry such as Chandra X-ray brightness, Hubble star positions, or Voyager plasma oscillations into audible pitch and amplitude. For the Perseus galaxy cluster black hole, pressure ripples were transposed upward by 57 octaves into human hearing.';
  }
  if (q.includes('eyes') || q.includes('solar system') || q.includes('orbit')) {
    return 'NASA/JPL Eyes on the Solar System renders live ephemerides from SPICE telemetry for planets, dwarf planets, and active spacecraft across past, real-time, and future epochs. Open the Solar System portal and switch to NASA/JPL 3D Eyes to inspect any body interactively.';
  }
  return `Space archive summary for "${prompt}": Explore live NASA Open API data across Daily Capture (APOD), DSCOVR EPIC Earth imagery, NeoWs near-Earth asteroids, DONKI solar alerts, and JPL Eyes on the Solar System directly inside Quantum Nest.`;
}

async function streamServerGemini(
  prompt: string,
  onChunk?: (partialText: string) => void
): Promise<{ text: string; model?: string; cached?: boolean } | null> {
  const res = await fetch('/api/hybrid-ai-stream', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ prompt }),
  });

  if (!res.ok || !res.body) return null;

  const reader = res.body.getReader();
  const decoder = new TextDecoder();
  let buffer = '';
  let accumulated = '';
  let detectedModel: string | undefined;
  let wasCached = false;

  while (true) {
    const { done, value } = await reader.read();
    if (done) break;
    buffer += decoder.decode(value, { stream: true });

    let sepIdx = buffer.indexOf('\n\n');
    while (sepIdx !== -1) {
      const eventBlock = buffer.slice(0, sepIdx);
      buffer = buffer.slice(sepIdx + 2);

      for (const line of eventBlock.split('\n')) {
        if (!line.startsWith('data:')) continue;
        const jsonStr = line.slice(5).trim();
        if (!jsonStr) continue;
        try {
          const evt = JSON.parse(jsonStr) as {
            chunk?: string;
            model?: string;
            done?: boolean;
            cached?: boolean;
            error?: string;
          };
          if (evt.model) detectedModel = evt.model;
          if (evt.cached) wasCached = true;
          if (evt.chunk) {
            accumulated += evt.chunk;
            onChunk?.(accumulated);
          }
          if (evt.error && !accumulated) {
            return null;
          }
        } catch {
          // ignore malformed partial frame
        }
      }

      sepIdx = buffer.indexOf('\n\n');
    }
  }

  return accumulated.trim()
    ? { text: accumulated, model: detectedModel, cached: wasCached }
    : null;
}

export async function askHybridSpaceGuide(
  prompt: string,
  forceMode: 'PREFER_ON_DEVICE' | 'ONLY_ON_DEVICE' | 'ONLY_IN_CLOUD' = 'PREFER_ON_DEVICE',
  onChunk?: (partialText: string) => void
): Promise<HybridAIResult> {
  const startTime = performance.now();
  const trimmedPrompt = prompt.trim();
  const cacheKey = `${forceMode}:${trimmedPrompt.toLowerCase()}`;

  // Fast client-side cache hit (bypassed when strictly benchmarking On-Device Nano)
  if (forceMode !== 'ONLY_ON_DEVICE') {
    const cached = readClientCache(cacheKey);
    if (cached) {
      onChunk?.(cached.text);
      return {
        ...cached,
        latencyMs: Math.max(1, Math.round(performance.now() - startTime)),
      };
    }
  }

  const mode: InferenceMode =
    forceMode === 'ONLY_ON_DEVICE'
      ? InferenceMode.ONLY_ON_DEVICE
      : forceMode === 'ONLY_IN_CLOUD'
      ? InferenceMode.ONLY_IN_CLOUD
      : InferenceMode.PREFER_ON_DEVICE;

  let firebaseErrorNote: string | undefined;

  // Check authentic on-device readiness up front to avoid wasting 700ms on blocked App Check in preview
  const cap = forceMode === 'PREFER_ON_DEVICE' ? await getOnDeviceCapability() : null;
  const shouldSkipFirebaseAutoHybrid =
    forceMode === 'PREFER_ON_DEVICE' &&
    firebaseCloudBlockedInSession &&
    !cap?.onDeviceReady;

  // Tier 1: Real Firebase AI Logic Hybrid Inference (Gemini Nano on-device -> Cloud Gemini 2.5 Flash)
  if (aiInstance && !shouldSkipFirebaseAutoHybrid) {
    try {
      const hybridParams: HybridParams = {
        mode,
        inCloudParams: {
          model: 'gemini-2.5-flash',
          systemInstruction: SYSTEM_INSTRUCTION,
        },
        onDeviceParams: {
          createOptions: {
            initialPrompts: [
              {
                role: 'system',
                content: [{ type: 'text', value: SYSTEM_INSTRUCTION }],
              },
            ],
          },
        },
      };

      const model = getGenerativeModel(aiInstance, hybridParams);
      const result = await model.generateContent(trimmedPrompt);
      const text = result.response.text();
      const latencyMs = Math.round(performance.now() - startTime);

      const isOnDevice =
        result.response.inferenceSource === InferenceSource.ON_DEVICE ||
        (forceMode === 'ONLY_ON_DEVICE' &&
          result.response.inferenceSource !== InferenceSource.IN_CLOUD);

      const out: HybridAIResult = {
        text: text || 'No response generated.',
        source: isOnDevice ? 'On-Device (Gemini Nano)' : 'Cloud Fallback (Gemini 2.5 Flash)',
        latencyMs,
      };
      onChunk?.(out.text);
      if (forceMode !== 'ONLY_ON_DEVICE') {
        writeClientCache(cacheKey, out);
      }
      return out;
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : String(err);
      firebaseErrorNote = msg;
      console.warn('Firebase AI Logic inference notice:', msg);

      if (
        msg.includes('App Check') ||
        msg.includes('app-check') ||
        msg.includes('401') ||
        msg.includes('403') ||
        msg.toLowerCase().includes('permission')
      ) {
        firebaseCloudBlockedInSession = false;
      }

      // Respect strict ONLY_ON_DEVICE mode so demos clearly show when Chrome Gemini Nano is absent
      if (forceMode === 'ONLY_ON_DEVICE') {
        return {
          text:
            'On-device Gemini Nano (Chrome Built-in Prompt API) is not available in this browser session. Switch routing to Auto Hybrid or Cloud Only for live Gemini streaming.',
          source: 'On-Device Unavailable',
          latencyMs: Math.round(performance.now() - startTime),
          fallbackReason: msg,
        };
      }
    }
  } else if (shouldSkipFirebaseAutoHybrid) {
    firebaseErrorNote = 'Preview App Check bypassed; streaming directly via server Gemini route.';
  }

  // Tier 2A: Server-side SSE Streaming Gemini (@google/genai) for sub-second first-token latency
  try {
    const streamed = await streamServerGemini(trimmedPrompt, onChunk);
    if (streamed?.text) {
      const out: HybridAIResult = {
        text: streamed.text,
        source: 'Server Streaming (Gemini)',
        latencyMs: Math.round(performance.now() - startTime),
        cached: streamed.cached,
        fallbackReason: firebaseErrorNote
          ? `Streamed via ${streamed.model || 'Gemini'} low-latency proxy.`
          : undefined,
      };
      writeClientCache(cacheKey, out);
      return out;
    }
  } catch {
    // proceed to Tier 2B non-streaming endpoint
  }

  // Tier 2B: Non-streaming Server Gemini fallback
  try {
    const serverRes = await fetch('/api/hybrid-ai-fallback', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ prompt: trimmedPrompt }),
    });
    if (serverRes.ok) {
      const data = (await serverRes.json()) as {
        available?: boolean;
        text?: string;
        model?: string;
        cached?: boolean;
      };
      if (data.available && data.text) {
        onChunk?.(data.text);
        const out: HybridAIResult = {
          text: data.text,
          source: 'Server Fallback (Gemini Cloud)',
          latencyMs: Math.round(performance.now() - startTime),
          cached: data.cached,
          fallbackReason: firebaseErrorNote
            ? `Answered via server ${data.model || 'Gemini'}.`
            : undefined,
        };
        writeClientCache(cacheKey, out);
        return out;
      }
    }
  } catch {
    // proceed to Tier 3 deterministic archive fallback
  }

  // Tier 3: Deterministic Astrophysical Archive Fallback
  const fallbackText = buildDomainFallbackText(trimmedPrompt);
  onChunk?.(fallbackText);
  return {
    text: fallbackText,
    source: 'Local Archive Fallback',
    latencyMs: Math.round(performance.now() - startTime),
    fallbackReason:
      firebaseErrorNote || 'Cloud inference unreachable; serving offline mission archive.',
  };
}
